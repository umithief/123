export function matchingCaptionTemplate(options: CaptionOptions): CaptionTemplate | undefined {
  return CAPTION_TEMPLATES.find((preset) =>
    Object.entries(preset.options).every(
      ([key, value]) => options[key as keyof CaptionOptions] === value,
    ),
  );
}
