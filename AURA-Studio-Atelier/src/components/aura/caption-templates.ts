export type CaptionTemplate = {
  id: string;
  name: string;
  category: "Sosyal" | "Müzik" | "Sinema" | "Sade";
  description: string;
  options: Partial<CaptionOptions>;
};
const { enabled: _enabled, offset: _offset, place: _place, ...appearance } = DEFAULT_CAPTIONS;
function template(
  id: string,
  name: string,
  category: CaptionTemplate["category"],
  description: string,
  patch: Partial<CaptionOptions>,
): CaptionTemplate {
  return { id, name, category, description, options: { ...appearance, ...patch } };
}

