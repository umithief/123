import { DEFAULT_CAPTIONS, type CaptionOptions } from "./captions.ts";

export type CaptionTemplate = {
  id: string;
  name: string;
  category: "İmza" | "Türler" | "Sosyal" | "Müzik" | "Sinema" | "Sade";
  description: string;
  options: Partial<CaptionOptions>;
};
// Templates set the look and the combo; the layered In/Out/Loop motion stays
// as the user chose it.
const {
  enabled: _enabled,
  offset: _offset,
  place: _place,
  motion: _motion,
  position: _position,
  ...appearance
} = DEFAULT_CAPTIONS;
function template(
  id: string,
  name: string,
  category: CaptionTemplate["category"],
  description: string,
  patch: Partial<CaptionOptions>,
): CaptionTemplate {
  return { id, name, category, description, options: { ...appearance, ...patch } };
}

