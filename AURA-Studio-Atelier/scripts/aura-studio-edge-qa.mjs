import { chromium } from 'playwright';
import assert from 'node:assert/strict';
import { useRuntimeAssetFetch } from './browser-runtime.mjs';
const url = process.argv[2] || 'http://127.0.0.1:8080/';
const browser = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH || '/usr/bin/chromium', args: ['--no-sandbox', '--disable-dev-shm-usage'] });
try {
  const page = await browser.newPage({ viewport: { width: 390, height: 844 } });
  const errors = [];
  page.on('pageerror', e => errors.push(e.message));
  await useRuntimeAssetFetch(page);
  await page.addInitScript(() => {
    const get = Storage.prototype.getItem, set = Storage.prototype.setItem;
    Storage.prototype.getItem = function(key) { if (key.startsWith('aura-')) throw new DOMException('Unavailable', 'SecurityError'); return get.call(this, key); };
    Storage.prototype.setItem = function(key, value) { if (key.startsWith('aura-')) throw new DOMException('Unavailable', 'QuotaExceededError'); return set.call(this, key, value); };
    navigator.mediaDevices.getUserMedia = async () => { throw new DOMException('Denied', 'NotAllowedError'); };
    Object.defineProperty(window, 'VideoEncoder', { value: undefined, configurable: true });
  });
  await page.goto(url);
  await page.waitForFunction(() => document.querySelector('.aura-studio')?.dataset.ready === 'true');
  await page.getByRole('button', { name: 'Mikrofon', exact: true }).click();
  await page.getByRole('alert').filter({ hasText: 'Mikrofon açılamadı' }).waitFor();
  await page.getByRole('button', { name: 'Hata mesajını kapat', exact: true }).click();
  await page.getByLabel('Müzik dosyası', { exact: true }).setInputFiles({ name: 'bad.mp3', mimeType: 'audio/mpeg', buffer: Buffer.from('not valid audio') });
  await page.getByRole('alert').filter({ hasText: 'Bu dosya çalınamadı' }).waitFor();
  await page.getByLabel('Müzik dosyası', { exact: true }).setInputFiles('/workspace/screenshots/aura-caption-track.wav');
  await page.getByRole('button', { name: 'Duraklat', exact: true }).click();
  await page.getByRole('tab', { name: 'Altyazı', exact: true }).click();
  const raw = Array.from({ length: 12 }, (_, i) => `${i+1}\n00:00:${String(i*3).padStart(2,'0')},000 --> 00:00:${String(i*3+2).padStart(2,'0')},000\nSatır ${i+1}\n`).join('\n');
  await page.getByLabel('SRT altyazı dosyası', { exact: true }).setInputFiles({ name: 'long.srt', mimeType: 'application/x-subrip', buffer: Buffer.from(raw) });
  await page.getByLabel('1. altyazı metni', { exact: true }).waitFor();
  assert.equal(await page.locator('textarea[aria-label$="altyazı metni"]').count(), 8);
  await page.getByRole('button', { name: 'Sonraki altyazı sayfası', exact: true }).click();
  assert.equal(await page.locator('textarea[aria-label$="altyazı metni"]').count(), 4);
  await page.getByRole('button', { name: '12. altyazıyı sil', exact: true }).click();
  await page.getByRole('button', { name: 'Geri al', exact: true }).click();
  assert.equal(await page.getByLabel('12. altyazı metni', { exact: true }).count(), 1);
  await page.getByRole('button', { name: 'Önceki altyazı sayfası', exact: true }).click();
  await page.getByLabel('1. altyazı bitişi', { exact: true }).fill('61');
  await page.getByLabel('1. altyazı metni', { exact: true }).focus();
  await page.getByRole('alert').filter({ hasText: 'Başlangıç bitişten' }).waitFor();
  assert.equal(await page.getByLabel('1. altyazı bitişi', { exact: true }).inputValue(), '2');
  await page.getByRole('button', { name: 'Tümünü temizle', exact: true }).click();
  await page.getByRole('button', { name: 'Geri al', exact: true }).click();
  assert.equal(await page.getByLabel('1. altyazı metni', { exact: true }).count(), 1);
  await page.getByRole('tab', { name: 'Proje', exact: true }).click();
  await page.getByRole('button', { name: 'Hazır ayarı kaydet', exact: true }).click();
  await page.getByRole('alert').filter({ hasText: 'Tarayıcı hazır ayarı saklayamadı' }).waitFor();
  await page.getByRole('button', { name: 'Oynat', exact: true }).click();
  await page.getByRole('button', { name: 'MP4 kaydet', exact: true }).click();
  await page.getByRole('alert').filter({ hasText: 'MP4 kaydı başlatılamadı' }).waitFor();
  assert.equal(await page.getByLabel('Video çözünürlüğü', { exact: true }).isDisabled(), false);
  assert.deepEqual(errors, []);
  console.log(JSON.stringify({ microphoneDenied: true, invalidAudio: true, restrictedStorage: true, subtitlePagination: true, undo: true, unsupportedEncoder: true, errors }));
} finally { await browser.close(); }
