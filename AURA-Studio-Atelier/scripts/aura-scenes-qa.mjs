import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { chromium } from "playwright";
import { useRuntimeAssetFetch } from "./browser-runtime.mjs";
import { unpackProject } from "../src/components/aura/project-archive.ts";
const url = process.argv[2] || "http://127.0.0.1:8080";
const tag = url.includes("8082") ? "android" : url.includes("8081") ? "built" : "dev";
const browser = await chromium.launch({ executablePath: "/usr/bin/chromium", args: ["--no-sandbox"] });
try {
  for (const width of (process.env.QA_WIDTHS || "390,1280").split(",").map(Number)) {
    const p = await browser.newPage({ viewport: { width, height: 844 }, hasTouch: width < 700, acceptDownloads: true });
    p.setDefaultTimeout(30000); await useRuntimeAssetFetch(p);
    const errors = []; p.on("pageerror", (e) => errors.push(e.message));
    await p.goto(url); await p.locator('.aura-studio[data-ready="true"]').waitFor();
    const chooser = p.waitForEvent("filechooser"); await p.locator('[data-intent="video"]').click();
    await (await chooser).setFiles("/workspace/screenshots/aura-scenes-fixture.mp4");
    await p.waitForFunction(() => document.querySelector(".aura-studio")?.getAttribute("data-tool") === "cuts");
    const panel = p.locator(".scene-panel"); await panel.locator("summary").click();
    const scan = () => panel.getByRole("button", { name: /^(Sahneleri bul|Yeniden tara)$/ }).click();
    await scan(); await panel.getByRole("button", { name: "İptal", exact: true }).click();
    await panel.getByRole("button", { name: "Sahneleri bul", exact: true }).waitFor();
    assert.equal(await panel.locator(".scene-results").count(), 0);
    await scan(); await panel.locator(".scene-results").waitFor();
    assert.equal(await panel.getByRole("checkbox").count(), 2);
    const times = await panel.locator(".scene-cut label span").allTextContents();
    assert.deepEqual(times, ["0:02.00", "0:04.00"]);
    await p.screenshot({ path: `/workspace/screenshots/scenes-${tag}-${width}-detected.png` });
    assert.ok(await panel.locator(".scene-cut img").evaluateAll((imgs) => imgs.every((img) => img.complete && img.naturalWidth > 0)));
    await panel.getByRole("button", { name: "Kesimi önizle 1", exact: true }).click();
    await panel.getByRole("checkbox").first().uncheck();
    await panel.getByRole("button", { name: "1 kesimi uygula", exact: true }).click();
    const save = async (suffix) => {
      const download = p.waitForEvent("download");
      await p.getByRole("button", { name: "Projeyi kaydet", exact: true }).click();
      const path = `/workspace/screenshots/scenes-${tag}-${width}-${suffix}.aura.zip`; await (await download).saveAs(path);
      const archive = await unpackProject(new Blob([readFileSync(path)])); return JSON.parse(await archive.get("project.json").text());
    };
    assert.deepEqual((await save("selected")).editor.clips.map((c) => [c.in,c.out]), [[0,4],[4,6]]);
    await p.getByRole("button", { name: "Son düzenlemeyi geri al", exact: true }).click();
    assert.equal((await save("undo")).editor.clips.length, 1);
    await scan(); await panel.locator(".scene-results").waitFor();
    await panel.getByRole("button", { name: "2 kesimi uygula", exact: true }).click();
    const data = await save("all");
    assert.deepEqual(data.editor.clips.map((c) => [c.in,c.out]), [[0,2],[2,4],[4,6]]);
    assert.equal(data.editor.clips.reduce((n,c) => n + (c.out - c.in) / c.rate, 0), 6);
    assert.equal(data.editor.media.filter((m) => m.sourceVideo).length, 1);
    await p.getByRole("button", { name: "Son düzenlemeyi geri al", exact: true }).click();
    await p.getByRole("button", { name: "Son düzenlemeyi yinele", exact: true }).click();
    assert.equal((await save("redo")).editor.clips.length, 3);
    await p.getByLabel("Kurgu yedek dosyası", { exact: true }).setInputFiles(`/workspace/screenshots/scenes-${tag}-${width}-redo.aura.zip`);
    await p.waitForFunction(() => document.querySelector(".aura-studio")?.getAttribute("data-tool") === "none");
    await p.locator('.atelier-navigation [data-workspace="edit"]').click();
    await p.locator('.aura-toolbar [data-tool="cuts"]').click();
    if (!await panel.evaluate((node) => node.open)) await panel.locator("summary").click();
    await p.waitForFunction(() => document.querySelectorAll(".timeline-clip").length === 3);
    assert.deepEqual((await save("restored")).editor.clips.map((c) => [c.in, c.out]), [[0,2],[2,4],[4,6]]);
    await scan(); await panel.locator(".scene-results").waitFor();
    assert.equal(await panel.getByRole("checkbox").count(), 0);
    await panel.getByLabel("Algılama hassasiyeti", { exact: true }).selectOption("high");
    assert.equal(await panel.locator(".scene-results").count(), 0);
    await p.screenshot({ path: `/workspace/screenshots/scenes-${tag}-${width}.png` });
    assert.equal(await p.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
    if (process.env.EXPORT_SCENES === "1" && width === 390) {
      await p.getByRole("button", { name: "Dışa aktar", exact: true }).click();
      const download = p.waitForEvent("download", { timeout: 60000 });
      await p.getByRole("button", { name: "Videoyu hazırla", exact: true }).click();
      await (await download).saveAs(`/workspace/screenshots/scenes-${tag}-${width}.mp4`);
      await p.getByRole("dialog").waitFor({ state: "hidden" });
    }
    await p.getByRole("button", { name: "Başlangıç", exact: true }).click();
    await p.getByRole("button", { name: "Switch to English", exact: true }).click();
    await p.getByRole("button", { name: "Continue", exact: true }).click();
    await p.getByRole("navigation", { name: "Workspaces", exact: true }).locator('[data-workspace="edit"]').click();
    await p.locator('.aura-toolbar [data-tool="cuts"]').click();
    await panel.getByText("Automatic scene splitting", { exact: true }).waitFor();
    if (!await panel.evaluate((node) => node.open)) await panel.locator("summary").click();
    const replace = p.waitForEvent("filechooser");
    await p.getByRole("button", { name: "Change track", exact: true }).click();
    await (await replace).setFiles("/workspace/screenshots/aura-easy-track.mp3");
    await p.waitForFunction(() => document.querySelector(".source-name span")?.textContent?.includes("aura-easy-track.mp3"));
    await p.getByRole("navigation", { name: "Workspaces", exact: true }).locator('[data-workspace="edit"]').click();
    await p.locator('.aura-toolbar [data-tool="cuts"]').click();
    if (!await panel.evaluate((node) => node.open)) await panel.locator("summary").click();
    await panel.getByText("Load a video as the main source to detect scenes.", { exact: true }).waitFor();
    assert.equal(await panel.getByRole("button", { name: "Find scenes", exact: true }).isDisabled(), true);
    assert.deepEqual(errors, []);
    console.log(JSON.stringify({ tag, width, boundaries: times, flashFiltered: true, cancellation: true, selectedCuts: true, undoRedo: true, restore: true, noDuplicateCuts: true, durationPreserved: true, english: true, errors }));
    await p.close();
  }
} finally { await browser.close(); }
